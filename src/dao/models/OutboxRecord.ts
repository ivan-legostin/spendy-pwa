import { ChangeLogEntry } from './ChangeLogEntry.ts';

/**
 * Запись исходящего журнала — изменение, ещё не отправленное в репозиторий.
 *
 * Обёртка над записью журнала нужна ради ключа.
 * Ключ требуется, чтобы после отправки удалить именно отправленное: очистить хранилище целиком нельзя —
 * пока идёт запрос к GitHub, пользователь может добавить транзакцию, и она пропадёт неотправленной.
 */
export interface OutboxRecord {
  /**
   * Порядковый номер, назначается базой данных автоматически.
   */
  sequence: number;
  /**
   * Сама запись журнала — в репозиторий уходит только она.
   */
  entry: ChangeLogEntry;
}
