/**
 * Итог обмена журналом с репозиторием.
 */
export interface ExchangeResult {
  /**
   * Сколько записей отправлено в репозиторий.
   */
  sentCount: number;
  /**
   * Сколько записей с других устройств применено к локальной БД.
   */
  appliedCount: number;
  /**
   * Сколько файлов журнала лежит в репозитории.
   */
  totalFileCount: number;
  /**
   * Пути файлов, которые пришлось прочитать: их версия разошлась с запомненной.
   */
  readPaths: string[];
  /**
   * Сколько строк не удалось разобрать. Ненулевое значение означает повреждение файла.
   */
  brokenLineCount: number;
}
